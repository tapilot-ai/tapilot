import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, cp, writeFile, rm, realpath } from 'node:fs/promises';
import { constants } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { runtimeLaunch, runtimeVersion } from '../server/runtime-client.mjs';

test('native plugin startup reuses matching managed code and Node, and ignores stale or invalid records', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'tapilot-runtime-launch-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const root = join(directory, 'native-plugin');
  const installations = join(directory, 'clients');
  const managed = join(installations, 'doubao/releases/runtime-test');
  const node = join(managed, 'bin', process.platform === 'win32' ? 'node.exe' : 'node');
  await mkdir(join(root, 'server'), { recursive: true });
  await mkdir(join(managed, 'server'), { recursive: true });
  await mkdir(join(managed, 'bin'));
  await cp(process.execPath, node, { mode: constants.COPYFILE_FICLONE });
  await writeFile(join(managed, 'server/runtime-server.mjs'), 'console.log(JSON.stringify({code:"managed",node:process.execPath}))');
  const record = { root: managed, runtime: { root: managed, node, version: '0.0.0' } };
  const recordFile = join(installations, 'doubao/installation.json');
  await writeFile(recordFile, JSON.stringify(record));
  assert.equal((await runtimeLaunch({ root, installations })).execPath, process.execPath);
  record.runtime.version = runtimeVersion;
  await writeFile(recordFile, JSON.stringify(record));
  const launch = await runtimeLaunch({ root, installations });
  const output = JSON.parse((await promisify(execFile)(launch.execPath, [fileURLToPath(launch.entry)])).stdout);
  assert.equal(output.code, 'managed');
  assert.equal(await realpath(output.node), await realpath(node));
  record.runtime.node = process.execPath;
  await writeFile(recordFile, JSON.stringify(record));
  assert.equal((await runtimeLaunch({ root, installations })).execPath, process.execPath, 'an entry outside its managed release is not adopted');
  await writeFile(recordFile, '{"root":null}');
  assert.equal((await runtimeLaunch({ root, installations })).execPath, process.execPath);
});
